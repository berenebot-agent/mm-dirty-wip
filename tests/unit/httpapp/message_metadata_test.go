func TestIMAPPreviewOnlyForNewArrivalsInBackground(t *testing.T) {
	t.Parallel()
	svc, _, u, _, box, fake := standaloneFixture(t)
	ctx := context.Background()
	rm := app.NewRemoteMailboxService(svc)
	t.Cleanup(rm.Stop)
	rm.SetRemoteDialer(func(context.Context, imap.Config) (app.RemoteSession, error) { return fake, nil })
	fake.add("INBOX", contractMIME, "<old@example.test>", "Old")
	if _, err := rm.ReconcileRemote(ctx, u.AccountID, box.ID); err != nil {
		t.Fatal(err)
	}
	w := app.NewRemoteWorker(svc, rm, nil)
	w.SetDemandInterval(-1)
	// The shared fixture may already have established an empty notification
	// baseline. Advance it to the imported backlog before detecting new mail.
	if _, ok, err := svc.Store.GetRemoteCursor(ctx, u.AccountID, box.ID, "INBOX"); err != nil {
		t.Fatal(err)
	} else if !ok {
		if err := svc.Store.EstablishRemoteBaseline(ctx, u.AccountID, box.ID, "INBOX", 100, 1); err != nil {
			t.Fatal(err)
		}
	} else if err := svc.Store.AdvanceRemoteCursor(ctx, u.AccountID, box.ID, "INBOX", 100, 1); err != nil {
		t.Fatal(err)
	}
	fake.add("INBOX", contractMIME, "<new@example.test>", "New")
	w.DetectInbox(ctx, box)
	queued, err := svc.Store.PendingRemotePreviews(ctx, 10)
	if err != nil || len(queued) != 1 || queued[0].RFCMessageID != "<new@example.test>" {
		t.Fatalf("new-only queue: %+v %v", queued, err)
	}
	srv := httpapp.New(svc, nil)
	srv.SetRemoteMailbox(rm)
	h := srv.Handler()
	_, key, err := svc.Store.CreateAPIKey(ctx, u.AccountID, "metadata", true, nil)
	if err != nil {
		t.Fatal(err)
	}
	get := func() []map[string]any {
		t.Helper()
		r := httptest.NewRequest("GET", "/v1/inboxes/"+box.ID+"/messages", nil)
		r.Header.Set("Authorization", "Bearer "+key)
		rr := httptest.NewRecorder()
		h.ServeHTTP(rr, r)
		if rr.Code != 200 {
			t.Fatalf("list: %d %s", rr.Code, rr.Body.String())
		}
		var page struct{ Items []map[string]any }
		if err := json.Unmarshal(rr.Body.Bytes(), &page); err != nil {
			t.Fatal(err)
		}
		return page.Items
	}
	for _, row := range get() {
		if row["snippet"] != "-" {
			t.Fatalf("preview generated by list: %+v", row)
		}
	}
	fake.mu.Lock()
	calls := fake.previewCalls
	fake.mu.Unlock()
	if calls != 0 {
		t.Fatalf("list/detection fetched a preview: %d", calls)
	}
	if n, err := rm.ProcessRemotePreviews(ctx); err != nil || n != 1 {
		t.Fatalf("background preview: %d %v", n, err)
	}
	if _, err := rm.ReconcileRemote(ctx, u.AccountID, box.ID); err != nil {
		t.Fatal(err)
	}
	for _, row := range get() {
		want := "-"
		if row["message_id"] == "<new@example.test>" {
			want = "contract body"
		}
		if row["snippet"] != want {
			t.Fatalf("preview lost on header refresh or old mail back-generated: %+v", row)
		}
	}
	if n, err := rm.ProcessRemotePreviews(ctx); err != nil || n != 0 {
		t.Fatalf("preview work repeated: %d %v", n, err)
	}
}

func TestGoogleDirectionUsesAllNativeLabels(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, folder, want string
		labels             []string
	}{
		{"sent to self", "INBOX", "outbound", []string{"INBOX", "SENT"}},
		{"draft", "DRAFT", "unknown", []string{"INBOX", "DRAFT"}},
		// A message with no system label is in no folder view: it is listed by
		// the unfiltered listing, not by an Archive folder.
		{"no system label", "", "unknown", []string{"Label_1"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			svc, _, u, _, _, _ := standaloneFixture(t)
			ctx := context.Background()
			box, err := svc.Store.CreateStandaloneInbox(ctx, u.AccountID, store.StandaloneCreate{Address: "google-direction@example.test"})
			if err != nil {
				t.Fatal(err)
			}
			rm := app.NewRemoteMailboxService(svc)
			t.Cleanup(rm.Stop)
			f := contractConnectorFixture(t, "google", tc.labels...)
			rm.Google = gmail.NewClient(f.Client())
			rm.Google.BaseURL = f.URL
			if err := rm.SaveGoogleGrant(ctx, u.AccountID, box.ID, "client", "secret", gmail.Token{AccessToken: "access", RefreshToken: "refresh", ExpiresIn: 3600, Scope: gmail.Scope}); err != nil {
				t.Fatal(err)
			}
			p := model.Principal{AccountID: u.AccountID, Admin: true}
			page, err := rm.ListRemoteMessages(ctx, p, box.ID, tc.folder, 25, "")
			if err != nil || len(page.Items) != 1 || page.Items[0].Direction != tc.want {
				t.Fatalf("direction=%+v err=%v", page, err)
			}
			source, ok, err := rm.ResolveRemoteReply(ctx, u.AccountID, page.Items[0].ID)
			if err != nil || !ok || source.Direction != tc.want {
				t.Fatalf("reply source=%+v err=%v", source, err)
			}
		})
	}
}

func TestRemoteDirectionAndSafeReplyDefaults(t *testing.T) {
	t.Parallel()
	svc, _, u, _, box, fake := standaloneFixture(t)
	ctx := context.Background()
	p := model.Principal{AccountID: u.AccountID, UserID: u.ID, Admin: true}
	fake.mu.Lock()
	fake.folders["Outgoing"] = 100
	fake.mu.Unlock()
	fake.add("INBOX", contractMIME, "<inbound@example.test>", "Inbound")
	fake.add("Sent", strings.ReplaceAll(contractMIME, "To: agent@remote.test", "To: peer@example.test"), "<outbound@example.test>", "Outbound")
	fake.add("Archive", contractMIME, "<unknown@example.test>", "Unknown")
	fake.add("Outgoing", contractMIME, "<mapped@example.test>", "Mapped")
	rm := app.NewRemoteMailboxService(svc)
	t.Cleanup(rm.Stop)
	rm.SetRemoteDialer(func(context.Context, imap.Config) (app.RemoteSession, error) { return fake, nil })
	rm.InstallRemoteBridges()
	if _, err := rm.ReconcileRemote(ctx, u.AccountID, box.ID); err != nil {
		t.Fatal(err)
	}
	folder, err := svc.Store.GetFolderByPath(ctx, u.AccountID, box.ID, "Outgoing")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := svc.Store.SetFolderRole(ctx, p, box.ID, folder.ID, model.FolderRoleSent); err != nil {
		t.Fatal(err)
	}
	srv := httpapp.New(svc, nil)
	srv.SetRemoteMailbox(rm)
	h := srv.Handler()
	_, key, err := svc.Store.CreateAPIKey(ctx, u.AccountID, "direction", true, nil)
	if err != nil {
		t.Fatal(err)
	}
	for folder, want := range map[string]string{"INBOX": "inbound", "Sent": "outbound", "Archive": "unknown", "Outgoing": "outbound"} {
		page, err := rm.ListRemoteMessages(ctx, p, box.ID, folder, 25, "")
		if err != nil || len(page.Items) != 1 || page.Items[0].Direction != want {
			t.Fatalf("%s direction: %+v %v", folder, page, err)
		}
		id := page.Items[0].ID
		source, ok, err := rm.ResolveRemoteReply(ctx, u.AccountID, id)
		if err != nil || !ok || source.Direction != want {
			t.Fatalf("reply source direction disagrees: %+v %v", source, err)
		}
		if folder == "Sent" {
			sent, err := svc.Send(ctx, p, app.SendInput{InboxID: box.ID, ReplyToMessageID: id, Text: "continue conversation"}, "")
			if err != nil || len(sent.Message.To) != 1 || sent.Message.To[0] != "peer@example.test" {
				t.Fatalf("outbound reply did not use original recipients: %+v %v", sent, err)
			}
		}
		if folder == "Archive" {
			r := httptest.NewRequest("POST", "/v1/messages/"+id+"/reply", strings.NewReader(`{"text":"reply"}`))
			r.Header.Set("Authorization", "Bearer "+key)
			r.Header.Set("Content-Type", "application/json")
			rr := httptest.NewRecorder()
			h.ServeHTTP(rr, r)
			if rr.Code != 400 || !strings.Contains(rr.Body.String(), "reply recipients are required") {
				t.Fatalf("unknown reply silently chose recipients: %d %s", rr.Code, rr.Body.String())
			}
			r = httptest.NewRequest("POST", "/v1/messages/"+id+"/reply", strings.NewReader(`{"to":["chosen@example.test"],"text":"explicit reply"}`))
			r.Header.Set("Authorization", "Bearer "+key)
			r.Header.Set("Content-Type", "application/json")
			rr = httptest.NewRecorder()
			h.ServeHTTP(rr, r)
			var result struct{ Message model.Message }
			if err := json.Unmarshal(rr.Body.Bytes(), &result); err != nil || rr.Code != 200 || len(result.Message.To) != 1 || result.Message.To[0] != "chosen@example.test" {
				t.Fatalf("explicit reply failed: %d %s %v", rr.Code, rr.Body.String(), err)
			}
			_, readerKey, err := svc.Store.CreateAPIKey(ctx, u.AccountID, "reader", false, map[string]string{box.ID: "read"})
			if err != nil {
				t.Fatal(err)
			}
			r = httptest.NewRequest("POST", "/v1/messages/"+id+"/reply", strings.NewReader(`{"to":["chosen@example.test"],"text":"forbidden reply"}`))
			r.Header.Set("Authorization", "Bearer "+readerKey)
			r.Header.Set("Content-Type", "application/json")
			rr = httptest.NewRecorder()
			h.ServeHTTP(rr, r)
			if rr.Code != 403 {
				t.Fatalf("inferred direction bypassed send permission: %d %s", rr.Code, rr.Body.String())
			}
			session, _, err := svc.Store.CreateSession(ctx, u.ID, time.Hour)
			if err != nil {
				t.Fatal(err)
			}
			for _, kind := range []string{"reply", "reply-all"} {
				r = httptest.NewRequest("GET", "/ui/messages/"+id+"/"+kind, nil)
				r.AddCookie(&http.Cookie{Name: "mmm_session", Value: session})
				rr = httptest.NewRecorder()
				h.ServeHTTP(rr, r)
				if rr.Code != 200 || !strings.Contains(rr.Body.String(), `name="to" value=""`) || !strings.Contains(rr.Body.String(), "Message direction is unknown") {
					t.Fatalf("%s UI guessed recipients: %d %s", kind, rr.Code, rr.Body.String())
				}
			}
		}
	}
}

// Public storage APIs expose the pending preview state without back-generating
// old rows; generated metadata survives subsequent header-only upserts.
func TestRemotePreviewFailureRetainsFallback(t *testing.T) {
	t.Parallel()
	svc, _, u, _, box, fake := standaloneFixture(t)
	ctx := context.Background()
	rec, err := svc.Store.UpsertRemoteMessage(ctx, u.AccountID, box.ID, store.RemoteMessageInput{FolderPath: "INBOX", UIDValidity: 100, UID: 99})
	if err != nil {
		t.Fatal(err)
	}
	if err := svc.Store.QueueRemotePreview(ctx, u.AccountID, box.ID, rec.ID); err != nil {
		t.Fatal(err)
	}
	rm := app.NewRemoteMailboxService(svc)
	t.Cleanup(rm.Stop)
	rm.SetRemoteDialer(func(context.Context, imap.Config) (app.RemoteSession, error) { return fake, nil })
	if n, err := rm.ProcessRemotePreviews(ctx); err != nil || n != 1 {
		t.Fatalf("failure should settle supplementary work: %d %v", n, err)
	}
	rec, err = svc.Store.GetRemoteMessage(ctx, u.AccountID, box.ID, rec.ID)
	if err != nil || rec.Snippet != "" {
		t.Fatalf("failed preview invented data: %+v %v", rec, err)
	}
}
